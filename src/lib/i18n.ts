export function t(key: string, params: Record<string, string | number> = {}): string {
  let s = messages[locale.value][key] ?? messages.fr[key] ?? key
  for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  return s
}

/** Texte d'un manifeste : chaîne simple ou { fr, en }. */
export function loc(value: Localized | null | undefined): string {
  if (value == null) return ''
  if (typeof value === 'string') return value
  return value[locale.value] ?? value.fr ?? value.en ?? Object.values(value)[0] ?? ''
}

export function category(id: string): string {
  const key = `cat.${id}`
  const s = t(key)
  return s === key ? id : s
}
